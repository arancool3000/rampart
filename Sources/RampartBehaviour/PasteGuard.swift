// MARK: - AI assessment contract (implemented by RampartAI)

public struct PasteAIVerdict: Codable, Sendable, Hashable {
    public enum Label: String, Codable, Sendable { case malicious, suspicious, benign }
    public var label: Label
    public var confidence: Int        // 0...100
    public var reasons: [String]
    public init(label: Label, confidence: Int, reasons: [String] = []) {
        self.label = label; self.confidence = max(0, min(100, confidence)); self.reasons = reasons
    }
}

/// Second opinion on a run-intended paste. Receives redacted text only. Return nil when unavailable.
public protocol PasteAIAssessor: Sendable {
    func assess(command: String, decoded: [String], sourceApp: String?) async -> PasteAIVerdict?
}

// MARK: - Decision

public enum PasteAction: String, Codable, Sendable { case allow, warn, block }

public struct PasteDecision: Sendable {
    public var action: PasteAction
    public var rule: String           // which row of the decision table applied
}

public struct PasteOutcome: Sendable {
    public var action: PasteAction
    public var decisionRule: String
    public var local: PasteLocalResult
    public var ai: PasteAIVerdict?
    public var aiTimedOut: Bool
    public var sourceApp: String?
    public var detection: Detection?
    public var blockedID: UUID?
}

/// A blocked paste kept in memory only (never written to disk) for "Show what was blocked" / "Restore".
public struct BlockedPaste: Sendable, Identifiable {
    public var id: UUID
    public var date: Date
    public var sourceApp: String?
    public var original: String
    public var detectionID: UUID
}

public struct PasteGuardConfig: Sendable {
    public var aiEnabled = true
    public var aiTimeout: TimeInterval = 4
    public var pollInterval: TimeInterval = 0.25
    /// Pasteboard types that mark content as private (password managers): never read or assessed.
    public var skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    public var maxBlockedKept = 20
    public init() {}
}

public enum PasteGuardDecision {
    /// Local verdict bands: ≥70 malicious, 40–69 suspicious, <40 benign.
    public static func localLabel(_ score: Int) -> PasteAIVerdict.Label { score >= 70 ? .malicious : score >= 40 ? .suspicious : .benign }

    /// Decision table (first matching row wins):
    /// B1 local ≥ 90 → block
    /// B2 AI malicious ≥ 85 confidence AND local ≥ 40 → block
    /// B3 AI malicious (any confidence) AND local malicious (≥ 70) → block
    /// B4 no AI verdict AND local ≥ 75 → block (wms-o5: fail closed on known-bad when the AI is unavailable)
    /// W1 local ≥ 40 → warn
    /// W2 AI malicious (any confidence) → warn
    /// W3 AI suspicious with confidence ≥ 60 → warn
    /// A1 otherwise → allow (pinned installers score 0 locally, so only rows W2/W3 can flag them)
    public static func decide(local: Int, ai: PasteAIVerdict?) -> PasteDecision {
        if local >= 90 { return .init(action: .block, rule: "B1 local≥90") }
        if let ai, ai.label == .malicious, ai.confidence >= 85, local >= 40 { return .init(action: .block, rule: "B2 AI malicious≥85 & local≥40") }
        if let ai, ai.label == .malicious, localLabel(local) == .malicious { return .init(action: .block, rule: "B3 both malicious") }
        // wms-o5: no AI opinion (off, no key, timed out, failed): known-bad local results (≥ 75, i.e. more than a
        // plain download-and-run) still block. Fail-open must not depend on the AI being reachable.
        if ai == nil, local >= 75 { return .init(action: .block, rule: "B4 no AI opinion & local≥75") }
        if local >= 40 { return .init(action: .warn, rule: "W1 local≥40") }
        if let ai, ai.label == .malicious { return .init(action: .warn, rule: "W2 AI malicious") }
        if let ai, ai.label == .suspicious, ai.confidence >= 60 { return .init(action: .warn, rule: "W3 AI suspicious≥60") }
        return .init(action: .allow, rule: "A1 allow")
    }
}

// MARK: - Pasteboard abstraction (lets tests use a private named pasteboard)

/// Mirror of NSPasteboard.AccessBehavior (macOS 15.4+ "Paste from Other Apps" setting for this app).
public enum PasteAccessBehavior: String, Sendable {
    case alwaysAllow   // contents may be read without a prompt
    case ask           // reading would prompt the user
    case `default`     // system default: reading would prompt the user
    case alwaysDeny    // reading is refused
}

/// What the app should show for PasteGuard.
public enum PasteGuardStatus: String, Sendable {
    case active            // reading allowed, guarding pastes
    case needsPermission   // ask/default: not reading; guide the user once to System Settings › Privacy & Security ›
                           // Paste from Other Apps › RamPart: Allow
    case denied            // alwaysDeny: PasteGuard disabled
    case stopped
}

public protocol PasteboardAccess: AnyObject {
    /// Non-prompting. Only `.alwaysAllow` permits `types`/`string()`.
    var accessBehavior: PasteAccessBehavior { get }
    /// Non-prompting detect API: does the first item look like a link? nil when unavailable.
    func detectLink() async -> Bool?
    var changeCount: Int { get }
    var types: [String] { get }
    func string() -> String?
    /// Replaces the content; returns the new changeCount.
    func replace(with text: String) -> Int
}

#if canImport(AppKit)
public final class SystemPasteboard: PasteboardAccess {
    public let pasteboard: NSPasteboard
    public init(_ pb: NSPasteboard = .general) { self.pasteboard = pb }
    public var accessBehavior: PasteAccessBehavior {
        // Privacy prompts apply to the general pasteboard only; private named pasteboards are ours.
        guard pasteboard.name == .general else { return .alwaysAllow }
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: return .alwaysAllow
            case .alwaysDeny: return .alwaysDeny
            case .ask: return .ask
            default: return .default
            }
        }
        return .alwaysAllow   // before 15.4 there is no paste prompt
    }
    public func detectLink() async -> Bool? {
        if #available(macOS 15.4, *) {
            guard let found = try? await pasteboard.detectedPatterns(for: [\.probableWebURL, \.links]) else { return nil }
            return found.contains(\.probableWebURL) || found.contains(\.links)
        }
        return nil
    }
    public var changeCount: Int { pasteboard.changeCount }
    public var types: [String] { (pasteboard.types ?? []).map(\.rawValue) }
    public func string() -> String? { pasteboard.string(forType: .string) }
    public func replace(with text: String) -> Int {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        return pasteboard.changeCount
    }
}
#endif

// MARK: - PasteGuard

/// Watches the clipboard of the logged-in user (run it in the per-user agent, not the root daemon).
/// Content that looks meant to be run is scored locally and, if enabled, by the AI assessor; really malicious
/// content is replaced on the clipboard with a harmless shell comment. Clipboard text is never logged or stored
/// on disk; only `BlockedPaste` keeps the original, in memory.
public final class PasteGuard: @unchecked Sendable {
    public var config: PasteGuardConfig
    public let classifier: PasteLocalClassifier
    public var ai: PasteAIAssessor?
    /// Detections to show (block = critical, warn = medium).
    public var onDetection: (@Sendable (Detection) -> Void)?
    /// Clipboard events for the BehaviourEngine (arms R31 with `paste_verdict`). Contains token hashes only.
    public var onEvent: (@Sendable (SecurityEvent) -> Void)?
    /// Name of the frontmost app at copy time (injected; defaults to NSWorkspace).
    public var sourceAppProvider: @Sendable () -> String?
    /// Access behaviour source (injectable for tests). Defaults to the pasteboard's own value.
    public var accessProvider: (() -> PasteAccessBehavior)?
    /// Status changes for the app (active / needsPermission / denied).
    public var onStatusChange: (@Sendable (PasteGuardStatus) -> Void)?
    public private(set) var status: PasteGuardStatus = .stopped
    /// Clipboard changes seen while not allowed to read (counts only).
    public private(set) var unreadChanges = 0
    /// Result of the non-prompting link detector for the last unread change.
    public private(set) var lastUnreadLooksLikeLink: Bool?

    private let board: PasteboardAccess
    private var lastChange: Int
    private var ownWrite: Int?
    private var blocked: [BlockedPaste] = []
    private var timer: DispatchSourceTimer?
    private let queue = DispatchQueue(label: "app.rampart.pasteguard")
    private let lock = NSLock()

    public init(pasteboard: PasteboardAccess, config: PasteGuardConfig = PasteGuardConfig(),
                classifier: PasteLocalClassifier = PasteClassifier(), ai: PasteAIAssessor? = nil) {
        self.board = pasteboard; self.config = config; self.classifier = classifier; self.ai = ai
        self.lastChange = pasteboard.changeCount
        #if canImport(AppKit)
        self.sourceAppProvider = { NSWorkspace.shared.frontmostApplication?.localizedName }
        #else
        self.sourceAppProvider = { nil }
        #endif
    }

    #if canImport(AppKit)
    /// Guard for the user's general pasteboard.
    public convenience init(config: PasteGuardConfig = PasteGuardConfig(), ai: PasteAIAssessor? = nil) {
        self.init(pasteboard: SystemPasteboard(), config: config, ai: ai)
    }
    #endif

    private func setLinkHint(_ l: Bool?) { lock.lock(); lastUnreadLooksLikeLink = l; lock.unlock() }

    func behaviour() -> PasteAccessBehavior { accessProvider?() ?? board.accessBehavior }

    private func setStatus(_ s: PasteGuardStatus) {
        lock.lock(); let changed = status != s; status = s; lock.unlock()
        if changed { onStatusChange?(s) }
    }

    /// Re-evaluates the access behaviour (call on app activation, e.g. after the user changed the setting).
    @discardableResult
    public func refreshStatus() -> PasteGuardStatus {
        switch behaviour() {
        case .alwaysAllow: setStatus(.active)
        case .ask, .default: setStatus(.needsPermission)
        case .alwaysDeny: setStatus(.denied)
        }
        return status
    }

    public func start() {
        if refreshStatus() == .denied { return }       // disabled; app reports it
        lock.lock(); defer { lock.unlock() }
        guard timer == nil else { return }
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now() + config.pollInterval, repeating: config.pollInterval, leeway: .milliseconds(50))
        t.setEventHandler { [weak self] in _ = self?.poll() }
        t.resume()
        timer = t
    }

    public func stop() { lock.lock(); timer?.cancel(); timer = nil; lock.unlock(); setStatus(.stopped) }

    /// Checks the pasteboard once. Returns the assessment task when new run-intended content was found.
    @discardableResult
    public func poll() -> Task<PasteOutcome, Never>? {
        // changeCount and accessBehavior never prompt; contents are read only with .alwaysAllow.
        lock.lock()
        let cc = board.changeCount
        guard cc != lastChange else { lock.unlock(); return nil }
        lastChange = cc
        if ownWrite == cc { lock.unlock(); return nil }
        lock.unlock()
        switch behaviour() {
        case .alwaysAllow:
            setStatus(.active)
        case .ask, .default:
            setStatus(.needsPermission)
            lock.lock(); unreadChanges += 1; lock.unlock()
            Task { [self] in let l = await board.detectLink(); setLinkHint(l) }
            return nil
        case .alwaysDeny:
            lock.lock(); timer?.cancel(); timer = nil; lock.unlock()
            setStatus(.denied)
            return nil
        }
        let types = Set(board.types)
        if !types.isDisjoint(with: config.skipTypes) { return nil }          // password managers
        guard let text = board.string(), PasteClassifier.isRunIntended(text) else { return nil }
        let source = sourceAppProvider()
        return Task { [self] in
            let outcome = await assess(text, sourceApp: source)
            enforce(outcome, text: text, changeCount: cc)
            return outcome
        }
    }

    /// Pure assessment (no clipboard changes). Exposed for the app's "check this command" feature and tests.
    public func assess(_ text: String, sourceApp: String?) async -> PasteOutcome {
        let local = classifier.classify(text)
        var verdict: PasteAIVerdict?
        var timedOut = false
        if config.aiEnabled, let ai, local.runIntended {
            let redacted = PasteClassifier.redact(text)
            let layers = local.decodedLayers.map(PasteClassifier.redact)
            let r = await Self.withTimeout(config.aiTimeout) { await ai.assess(command: redacted, decoded: layers, sourceApp: sourceApp) }
            switch r { case .value(let v): verdict = v; case .timedOut: timedOut = true }
        }
        let d = PasteGuardDecision.decide(local: local.score, ai: verdict)
        var outcome = PasteOutcome(action: d.action, decisionRule: d.rule, local: local, ai: verdict, aiTimedOut: timedOut,
                                   sourceApp: sourceApp, detection: nil, blockedID: nil)
        if d.action != .allow { outcome.detection = detection(for: outcome, text: text) }
        return outcome
    }

    enum TimedResult<T> { case value(T), timedOut }

    static func withTimeout<T: Sendable>(_ seconds: TimeInterval, _ op: @escaping @Sendable () async -> T) async -> TimedResult<T> {
        await withTaskGroup(of: TimedResult<T>.self) { g in
            g.addTask { .value(await op()) }
            g.addTask { try? await Task.sleep(nanoseconds: UInt64(seconds * 1e9)); return .timedOut }
            let first = await g.next() ?? .timedOut
            g.cancelAll()
            return first
        }
    }

    public static func replacementText(sourceApp: String?) -> String {
        "# RamPart blocked a dangerous command copied from \(sourceApp ?? "an app"). Open RamPart for details."
    }

    private func enforce(_ o: PasteOutcome, text: String, changeCount: Int) {
        var o = o
        if o.action == .block {
            lock.lock()
            // Only replace if the user has not copied something else meanwhile.
            if board.changeCount == changeCount {
                let newCC = board.replace(with: Self.replacementText(sourceApp: o.sourceApp))
                ownWrite = newCC; lastChange = newCC
                let b = BlockedPaste(id: UUID(), date: Date(), sourceApp: o.sourceApp, original: text, detectionID: o.detection?.id ?? UUID())
                blocked.append(b)
                if blocked.count > config.maxBlockedKept { blocked.removeFirst(blocked.count - config.maxBlockedKept) }
                o.blockedID = b.id
            }
            lock.unlock()
        }
        if let d = o.detection { onDetection?(d) }
        if o.action != .allow {
            onEvent?(SecurityEvent(kind: .other, detail: [
                "type": "clipboard", "class": "risky", "source_app": o.sourceApp ?? "",
                "clip_tokens": ClipboardFingerprint.fingerprint(text),
                "paste_verdict": o.action == .block ? "malicious" : "suspicious",
                "paste_score": String(o.local.score)], source: "pasteguard"))
        }
    }

    private func detection(for o: PasteOutcome, text: String) -> Detection {
        var ev: [Evidence] = []
        let local = o.local
        ev.append(Evidence(source: .behaviour, title: "Local check: score \(local.score)",
                           detail: local.reasons.isEmpty ? "No specific risky behaviour recognised." : "The command " + local.reasons.joined(separator: "; ") + ".",
                           score: local.score))
        if let ai = o.ai {
            ev.append(Evidence(source: .behaviour, title: "AI check: \(ai.label.rawValue) (\(ai.confidence)% confident)",
                               detail: ai.reasons.isEmpty ? "No reasons given." : ai.reasons.joined(separator: "; "), score: ai.label == .benign ? 0 : ai.confidence))
        } else if o.aiTimedOut {
            ev.append(Evidence(source: .behaviour, title: "AI check timed out", detail: "Decision made from the local check only.", score: 0))
        }
        ev.append(Evidence(source: .behaviour, title: "Decision \(o.decisionRule)",
                           detail: "Copied from \(o.sourceApp ?? "an unknown app"). Redacted preview: \(PasteClassifier.redact(text).prefix(160))", score: 0))
        let blocking = o.action == .block
        let conf = max(local.score, o.ai.map { $0.label == .benign ? 0 : $0.confidence } ?? 0)
        return Detection(name: blocking ? "Dangerous pasted command blocked" : "Suspicious command on the clipboard",
                         category: local.categories.contains(.credentialAccess) || local.categories.contains(.passwordLure) ? .infostealer : (blocking ? .malware : .suspicious),
                         severity: blocking ? .critical : .medium, confidence: blocking ? max(conf, 90) : min(conf, 74), evidence: ev)
    }

    // MARK: blocked items (memory only)

    public var blockedItems: [BlockedPaste] { lock.lock(); defer { lock.unlock() }; return blocked }

    /// Puts a blocked command back on the clipboard. The app must ask the user first and pass `confirmed: true`.
    @discardableResult
    public func restore(id: UUID, confirmed: Bool) -> Bool {
        guard confirmed else { return false }
        lock.lock(); defer { lock.unlock() }
        guard let i = blocked.firstIndex(where: { $0.id == id }) else { return false }
        let b = blocked.remove(at: i)
        let cc = board.replace(with: b.original)
        ownWrite = cc; lastChange = cc
        return true
    }

    /// Forgets blocked originals (e.g. on logout or when the user dismisses them).
    public func clearBlocked() { lock.lock(); blocked.removeAll(); lock.unlock() }
}
