import Foundation
import AppKit
import CoreGraphics

/// Locks the vault automatically: after `idleMinutes` without keyboard/mouse input (system-wide idle),
/// when the Mac sleeps, when the screen locks or the screensaver starts, and when the user switches away
/// (fast user switching). Owners call `start()` once the vault is unlocked and `stop()` when locked.
@MainActor
public final class AutoLock {
    public var idleMinutes: Int
    public var lockOnSleep: Bool
    public var lockOnScreenLock: Bool
    private let onLock: () -> Void
    private var timer: Timer?
    private var tokens: [(NotificationCenter, NSObjectProtocol)] = []

    public init(idleMinutes: Int = 5, lockOnSleep: Bool = true, lockOnScreenLock: Bool = true, onLock: @escaping () -> Void) {
        self.idleMinutes = idleMinutes; self.lockOnSleep = lockOnSleep; self.lockOnScreenLock = lockOnScreenLock; self.onLock = onLock
    }

    public func start() {
        stop()
        let ws = NSWorkspace.shared.notificationCenter
        let dist = DistributedNotificationCenter.default()
        func observe(_ c: NotificationCenter, _ name: Notification.Name, when: @escaping @MainActor (AutoLock) -> Bool) {
            let t = c.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { if let self, when(self) { self.fire() } }
            }
            tokens.append((c, t))
        }
        observe(ws, NSWorkspace.willSleepNotification) { $0.lockOnSleep }
        observe(ws, NSWorkspace.screensDidSleepNotification) { $0.lockOnScreenLock }
        observe(ws, NSWorkspace.sessionDidResignActiveNotification) { _ in true }
        observe(dist, Notification.Name("com.apple.screenIsLocked")) { $0.lockOnScreenLock }
        observe(dist, Notification.Name("com.apple.screensaver.didstart")) { $0.lockOnScreenLock }
        timer = Timer.scheduledTimer(withTimeInterval: 15, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkIdle() }
        }
    }

    public func stop() {
        timer?.invalidate(); timer = nil
        for (c, t) in tokens { c.removeObserver(t) }
        tokens = []
    }

    /// Seconds since the last keyboard or mouse event anywhere in the login session.
    public static var systemIdleSeconds: Double {
        CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: CGEventType(rawValue: ~0)!)
    }

    private func checkIdle() {
        guard idleMinutes > 0 else { return }
        if Self.systemIdleSeconds >= Double(idleMinutes * 60) { fire() }
    }

    private func fire() { stop(); onLock() }
}

/// Copies secrets to the pasteboard marked as concealed and transient (so clipboard managers that honour
/// the nspasteboard.org conventions skip them) and clears them after a delay if they are still there.
@MainActor
public final class ClipboardGuard {
    public static let shared = ClipboardGuard()
    private var pending: DispatchWorkItem?
    public private(set) var clearsAt: Date?

    public func copy(_ secret: String, clearAfter seconds: Int = 30) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(secret, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let count = pb.changeCount
        pending?.cancel()
        guard seconds > 0 else { clearsAt = nil; return }
        clearsAt = Date().addingTimeInterval(Double(seconds))
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated {
                // Only clear if nobody copied something else in the meantime.
                if NSPasteboard.general.changeCount == count { NSPasteboard.general.clearContents() }
                self?.clearsAt = nil
            }
        }
        pending = work
        DispatchQueue.main.asyncAfter(deadline: .now() + .seconds(seconds), execute: work)
    }

    /// Clears now if the pasteboard still holds what we put there (used on lock and quit).
    public func clearIfOurs() {
        guard clearsAt != nil else { return }
        pending?.cancel(); pending = nil; clearsAt = nil
        let pb = NSPasteboard.general
        if pb.types?.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")) == true { pb.clearContents() }
    }
}
